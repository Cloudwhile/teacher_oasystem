import fs from "node:fs";
import path from "node:path";

const rootDir = path.resolve(import.meta.dirname, "..");
const tokensPath = path.join(rootDir, "design-tokens.json");
const cssOutPath = path.join(rootDir, "src/styles/tokens.css");
const slintOutPath = path.resolve(
	rootDir,
	"../crates/desktop_manager/ui/tokens.slint",
);

const tokens = JSON.parse(fs.readFileSync(tokensPath, "utf8"));
const { primitive, semantic, dark } = tokens;

function refToCssVar(value) {
	if (
		typeof value === "string" &&
		value.startsWith("{") &&
		value.endsWith("}")
	) {
		const parts = value.slice(1, -1).split(".");
		return `var(--${parts.join("-")})`;
	}
	return value;
}

function resolveHex(value) {
	if (
		typeof value === "string" &&
		value.startsWith("{") &&
		value.endsWith("}")
	) {
		const parts = value.slice(1, -1).split(".");
		let cur = primitive;
		for (const part of parts) {
			cur = cur?.[part];
		}
		if (typeof cur !== "string") {
			throw new Error(`Unresolved token reference: ${value}`);
		}
		return cur;
	}
	return value;
}

function buildDarkDecls(indent) {
	const lines = [];
	for (const [key, val] of Object.entries(dark.color)) {
		lines.push(`${indent}--color-${key}: ${val};`);
	}
	for (const [key, val] of Object.entries(dark.shadow)) {
		lines.push(`${indent}--shadow-${key}: ${val};`);
	}
	for (const [key, val] of Object.entries(dark.ring)) {
		lines.push(`${indent}--ring-${key}: ${val};`);
	}
	return lines.join("\n");
}

function pxToRem(pxStr) {
	if (typeof pxStr === "string" && pxStr.endsWith("px")) {
		const rem = Number.parseFloat(pxStr) / 16;
		return `${Number(rem.toFixed(4))}rem`;
	}
	return pxStr;
}

function generateCss() {
	const lines = [
		"/* Generated by scripts/sync-tokens.mjs from design-tokens.json. Do not hand-edit. */",
		":root {",
		"\tcolor-scheme: light dark;",
		"",
		"\t/* primitive */",
	];

	for (const [ramp, stops] of Object.entries(primitive.color)) {
		for (const [stop, hex] of Object.entries(stops)) {
			lines.push(`\t--color-${ramp}-${stop}: ${hex};`);
		}
	}
	for (const [group, entries] of Object.entries(primitive)) {
		if (group === "color") continue;
		for (const [key, val] of Object.entries(entries)) {
			const cssVal = group === "text" ? pxToRem(val) : val;
			lines.push(`\t--${group}-${key}: ${cssVal};`);
		}
	}

	lines.push("", "\t/* semantic (light default, referencing primitives) */");
	for (const [key, val] of Object.entries(semantic.color)) {
		lines.push(`\t--color-${key}: ${refToCssVar(val)};`);
	}
	for (const [key, val] of Object.entries(semantic.ring)) {
		lines.push(`\t--ring-${key}: ${val};`);
	}
	lines.push("}", "");

	lines.push(
		':root:has(> head > meta[name="color-scheme"][content="light"]),',
		':root[data-theme="light"] {',
		"\tcolor-scheme: light;",
		"}",
		"",
		':root:has(> head > meta[name="color-scheme"][content="dark"]),',
		':root[data-theme="dark"] {',
		"\tcolor-scheme: dark;",
		buildDarkDecls("\t"),
		"}",
		"",
		"@media (prefers-color-scheme: dark) {",
		'\t:root:not([data-theme="light"]):not(:has(> head > meta[name="color-scheme"][content="light"])) {',
		buildDarkDecls("\t\t"),
		"\t}",
		"}",
		"",
		"@media (prefers-contrast: more) {",
		"\t:root {",
		"\t\t--color-border: var(--color-neutral-400);",
		"\t\t--color-border-strong: var(--color-neutral-600);",
		"\t\t--color-text-muted: var(--color-neutral-800);",
		"\t\t--color-icon: var(--color-neutral-700);",
		"\t}",
		'\t:root:has(> head > meta[name="color-scheme"][content="dark"]),',
		'\t:root[data-theme="dark"] {',
		"\t\t--color-border: #5a6478;",
		"\t\t--color-border-strong: #848d9d;",
		"\t\t--color-text-muted: #d6dbe4;",
		"\t\t--color-icon: #c5cad4;",
		"\t}",
		"\t@media (prefers-color-scheme: dark) {",
		'\t\t:root:not([data-theme="light"]):not(:has(> head > meta[name="color-scheme"][content="light"])) {',
		"\t\t\t--color-border: #5a6478;",
		"\t\t\t--color-border-strong: #848d9d;",
		"\t\t\t--color-text-muted: #d6dbe4;",
		"\t\t\t--color-icon: #c5cad4;",
		"\t\t}",
		"\t}",
		"}",
		"",
	);

	return lines.join("\n");
}

function remToPx(remStr) {
	if (remStr.endsWith("rem")) {
		return `${Math.round(Number.parseFloat(remStr) * 16)}px`;
	}
	return remStr;
}

function generateSlint() {
	const lines = [
		"// Generated by frontend-panel/scripts/sync-tokens.mjs from design-tokens.json. Do not hand-edit.",
		"export global Theme {",
	];

	for (const [ramp, stops] of Object.entries(primitive.color)) {
		lines.push(`    // ${ramp} ramp`);
		for (const [stop, hex] of Object.entries(stops)) {
			lines.push(`    out property <color> ${ramp}-${stop}: ${hex};`);
		}
		lines.push("");
	}

	lines.push("    // Semantic surfaces, text & actions");
	for (const [key, val] of Object.entries(semantic.color)) {
		lines.push(`    out property <color> ${key}: ${resolveHex(val)};`);
	}
	lines.push("");

	lines.push("    // Spacing scale (§3.2.2)");
	for (const step of ["1", "2", "3", "4", "6", "8", "12", "16"]) {
		lines.push(
			`    out property <length> space-${step}: ${primitive.space[step]};`,
		);
	}
	lines.push("");

	lines.push("    // Type scale (§4.1.1d) & weights (§2.2.b)");
	for (const step of ["xs", "sm", "base", "lg", "xl", "2xl"]) {
		lines.push(
			`    out property <length> text-${step}: ${primitive.text[step]};`,
		);
	}
	lines.push(
		`    out property <int> weight-normal: ${primitive.weight.normal};`,
	);
	lines.push(
		`    out property <int> weight-semibold: ${primitive.weight.semibold};`,
	);
	lines.push("");

	lines.push(
		"    // Radii (§1.4.3) — aligned with web radius-sm / radius-DEFAULT / radius-lg",
	);
	lines.push(
		`    out property <length> radius-sm: ${remToPx(primitive.radius.sm)};`,
	);
	lines.push(
		`    out property <length> radius-default: ${remToPx(primitive.radius.DEFAULT)};`,
	);
	lines.push(
		`    out property <length> radius-md: ${remToPx(primitive.radius.DEFAULT)};`,
	);
	lines.push(
		`    out property <length> radius-lg: ${remToPx(primitive.radius.lg)};`,
	);
	lines.push("");

	lines.push("    // Elevation & shadows (§6.2.1)");
	lines.push("    out property <color> shadow-subtle: #1011140a;");
	lines.push("}", "");

	return lines.join("\n");
}

fs.writeFileSync(cssOutPath, generateCss(), "utf8");
fs.writeFileSync(slintOutPath, generateSlint(), "utf8");
console.log("Synced tokens.css and tokens.slint from design-tokens.json.");
